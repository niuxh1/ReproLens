import { readdir, readFile, stat } from 'node:fs/promises';
import { join, relative } from 'node:path';
import type { Analyzer } from './analyzer.js';
import type { Claim, Diagnosis, ExperimentPlan, Paper, RepoSummary, Run } from '../domain/types.js';

const claimLine = /^\s*claim\s+([A-Za-z0-9_-]+)\s*[:：]\s*(.+)$/i;
const metricBefore = /([-+]?(?:\d+(?:\.\d*)?|\.\d+))\s+(?:[A-Za-z-]+\s+){0,3}(errors?|tasks?|papers?|counts?|iterations?)\b/i;
const metricAfter = /\b(accuracy|f1(?:[-\s]?score)?|auc|precision|recall|loss|mae|rmse|rouge(?:-l)?|bleu|errors|error|count|tasks|papers)\b[^0-9+\-.]{0,24}([-+]?(?:\d+(?:\.\d*)?|\.\d+))/i;
const tolerance = /(?:tolerance\s*[:=]?\s*(?:±|\+\/-)?|±|\+\/-)\s*([0-9]*\.?[0-9]+)/i;
const runLine = /^\s*(?:run|command)\s*[:：]\s*`?\s*(.+?)\s*`?\s*$/i;
const codeCommand = /^\s*(python(?:3)?|pytest|rscript|bash|sh|go\s+test)\b.+$/i;
const seedCommand = /--seed\s+(\d+)/i;
const seedText = /\bseed\s*[:=]?\s*(\d+)\b/i;
const seedError = /seed\s*mismatch[^\n]*?expected\s+(\d+)[^\n]*?got\s+(\d+)/i;

export class HeuristicAnalyzer implements Analyzer {
  async extractClaims(paper: Paper, _repo: RepoSummary): Promise<Claim[]> {
    const claims: Claim[] = [];
    const seenIds = new Set<string>();
    const lines = paper.text.split(/\r?\n/);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index]!.trim();
      if (!line) continue;
      let id = '';
      let text = line;
      const explicit = claimLine.exec(line);
      if (explicit) {
        id = explicit[1]!.toUpperCase();
        text = explicit[2]!.trim();
      }
      let metric = '';
      let rawValue = '';
      const before = metricBefore.exec(text);
      if (before) {
        rawValue = before[1]!;
        metric = before[2]!;
      } else {
        const after = metricAfter.exec(text);
        if (!after) continue;
        rawValue = after[2]!;
        metric = after[1]!;
      }
      if (!id) id = `C${claims.length + 1}`;
      if (seenIds.has(id)) id = `${id}-${index + 1}`;
      seenIds.add(id);
      const value = Number(rawValue);
      if (!Number.isFinite(value)) continue;
      let absTolerance = 0.01;
      const toleranceMatch = tolerance.exec(text);
      if (toleranceMatch) {
        const parsed = Number(toleranceMatch[1]);
        if (Number.isFinite(parsed) && parsed > 0) absTolerance = parsed;
      }
      claims.push({
        claim_id: id,
        text,
        metric: normalizeMetric(metric),
        expected_value: value,
        tolerance: { abs: absTolerance, rel: 0 },
        source: { path: paper.source_path, line: index + 1, quote: line },
        selected: false,
      });
    }
    if (claims.length === 0) throw new Error('no measurable claim found in paper');
    return dedupeClaims(claims);
  }

  async buildPlan(claim: Claim, paper: Paper, repo: RepoSummary): Promise<ExperimentPlan> {
    const command = findCommand(paper.text) || findCommand(repo.readme ?? '') || repo.command_candidates[0]?.trim() || 'python run_experiment.py';
    let seed = 42;
    const commandSeed = seedCommand.exec(command);
    if (commandSeed) seed = Number(commandSeed[1]);
    else {
      const textSeed = seedText.exec(paper.text);
      if (textSeed) seed = Number(textSeed[1]);
    }
    const metric = normalizeMetric(claim.metric);
    return {
      id: `plan_${claim.claim_id.toLowerCase()}`,
      claim_id: claim.claim_id,
      command,
      image: 'python:3.11-slim',
      work_dir: '.',
      seed,
      expected_metric: metric,
      expected_value: claim.expected_value,
      tolerance: claim.tolerance,
      metric_source: {
        kind: 'stdout_regex',
        pattern: `(?i)${escapeRegex(metric)}\\s*[:=]\\s*([-+]?(?:\\d+(?:\\.\\d*)?|\\.\\d+))`,
        key: metric,
      },
      notes: 'Generated by the deterministic offline analyzer.',
      confirmed: false,
    };
  }

  async diagnose(run: Run, _repo: RepoSummary, workspace: string): Promise<Diagnosis> {
    const output = `${run.stderr ?? ''}\n${run.stdout ?? ''}`;
    if (run.status === 'timeout') {
      return {
        failure_class: 'timeout',
        root_cause: 'The experiment exceeded the configured execution timeout.',
        confidence: 'high',
        explanation: 'No patch is proposed automatically for a timeout; inspect resource usage and command scope.',
      };
    }
    const seed = seedError.exec(output);
    if (seed) {
      const want = Number(seed[1]);
      const got = Number(seed[2]);
      const found = await findSeedPatch(workspace, got, want);
      if (found) {
        return {
          failure_class: 'seed_mismatch',
          root_cause: `The code uses seed ${got} while the experiment plan requires seed ${want}.`,
          confidence: 'high',
          patch_diff: found.diff,
          explanation: `Change ${found.file} from SEED = ${got} to SEED = ${want} without altering the data split or metric.`,
        };
      }
    }
    const lower = output.toLowerCase();
    if (lower.includes('modulenotfounderror') || lower.includes('no module named')) {
      return { failure_class: 'dependency_missing', root_cause: 'A required Python package is not available in the runtime.', confidence: 'high', explanation: 'Pin the dependency in the project environment; no automatic patch is proposed.', needs_code_agent: true };
    }
    if (lower.includes('filenotfounderror') || lower.includes('no such file or directory')) {
      return { failure_class: 'path_error', root_cause: 'The command references a missing file or directory.', confidence: 'medium', explanation: 'Check the workspace-relative data and configuration paths before patching.', needs_code_agent: true };
    }
    if (lower.includes('notimplementederror') || lower.includes('not implemented')) {
      return { failure_class: 'missing_implementation', root_cause: 'The experiment requires an implementation that is not present in the repository.', confidence: 'high', explanation: 'Delegate the missing implementation to a configured code agent.', needs_code_agent: true };
    }
    if (lower.includes('syntaxerror')) {
      return { failure_class: 'syntax_error', root_cause: 'The repository contains a syntax error.', confidence: 'high', explanation: 'No automatic patch is proposed; inspect the reported source location.', needs_code_agent: true };
    }
    return { failure_class: 'unknown', root_cause: 'The failure did not match a supported deterministic pattern.', confidence: 'low', explanation: 'Inspect the preserved stdout/stderr and run manifest.', needs_code_agent: true };
  }
}

function dedupeClaims(claims: Claim[]): Claim[] {
  const out: Claim[] = [];
  const index = new Map<string, number>();
  for (const claim of claims) {
    const key = `${claim.metric}:${claim.expected_value}`;
    const existingIndex = index.get(key);
    if (existingIndex === undefined) {
      index.set(key, out.length);
      out.push(claim);
      continue;
    }
    const current = out[existingIndex]!;
    const explicitNew = (claim.source.quote ?? '').trim().toLowerCase().startsWith('claim ');
    const explicitOld = (current.source.quote ?? '').trim().toLowerCase().startsWith('claim ');
    if (claim.tolerance.abs > current.tolerance.abs || (claim.tolerance.abs === current.tolerance.abs && explicitNew && !explicitOld)) {
      if (explicitNew && !explicitOld) claim.claim_id = current.claim_id;
      out[existingIndex] = claim;
    }
  }
  return out;
}

function findCommand(text: string): string {
  const lines = text.split(/\r?\n/);
  for (const raw of lines) {
    const match = runLine.exec(raw);
    if (match) return match[1]!.replace(/^`+|`+$/g, '').trim();
  }
  for (const raw of lines) {
    const line = raw.trim().replace(/^`+|`+$/g, '');
    if (codeCommand.test(line)) return line;
  }
  return '';
}

function normalizeMetric(metric: string): string {
  const normalized = metric.trim().toLowerCase().replace(/\s+/g, '-');
  return normalized === 'f1-score' || normalized === 'f1score' ? 'f1' : normalized;
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function findSeedPatch(workspace: string, got: number, want: number): Promise<{ diff: string; file: string } | null> {
  const root = workspace;
  const entries = await readdir(root, { recursive: true, withFileTypes: true }).catch(() => []);
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith('.py')) continue;
    const full = join(entry.parentPath ?? root, entry.name);
    const info = await stat(full);
    if (info.size > 2 * 1024 * 1024) continue;
    const content = (await readFile(full, 'utf8')).replace(/\r\n/g, '\n');
    const pattern = new RegExp(`^(\\s*SEED\\s*=\\s*)${got}(\\s*)$`, 'm');
    if (!pattern.test(content)) continue;
    const updated = content.replace(pattern, `$1${want}$2`);
    const oldLines = content.replace(/\n$/, '').split('\n');
    const newLines = updated.replace(/\n$/, '').split('\n');
    const rel = relative(root, full).split('\\').join('/');
    const diff = [`--- a/${rel}`, `+++ b/${rel}`, `@@ -1,${oldLines.length} +1,${newLines.length} @@`];
    for (let index = 0; index < oldLines.length; index += 1) {
      if (oldLines[index] === newLines[index]) diff.push(` ${oldLines[index]}`);
      else {
        diff.push(`-${oldLines[index]}`);
        diff.push(`+${newLines[index]}`);
      }
    }
    return { diff: `${diff.join('\n')}\n`, file: rel };
  }
  return null;
}
