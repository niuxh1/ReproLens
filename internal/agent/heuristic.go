package agent

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"reprolens/internal/domain"
)

type Heuristic struct{}

func NewHeuristic() *Heuristic { return &Heuristic{} }

var (
	claimLineRE    = regexp.MustCompile(`(?i)^\s*claim\s+([A-Za-z0-9_-]+)\s*[:：]\s*(.+)$`)
	metricBeforeRE = regexp.MustCompile(`(?i)([-+]?(?:\d+(?:\.\d*)?|\.\d+))\s+(?:[A-Za-z-]+\s+){0,3}(errors?|tasks?|papers?|counts?|iterations?)\b`)
	metricRE       = regexp.MustCompile(`(?i)\b(accuracy|f1(?:[-\s]?score)?|auc|precision|recall|loss|mae|rmse|rouge(?:-l)?|bleu|errors|error|count|tasks|papers)\b[^0-9+\-.]{0,24}([-+]?(?:\d+(?:\.\d*)?|\.\d+))`)
	toleranceRE    = regexp.MustCompile(`(?i)(?:tolerance\s*[:=]?\s*(?:±|\+/-)?|±|\+/-)\s*([0-9]*\.?[0-9]+)`)
	runLineRE      = regexp.MustCompile(`(?i)^\s*(?:run|command)\s*[:：]\s*` + "`?" + `\s*(.+?)\s*` + "`?" + `\s*$`)
	codeCmdRE      = regexp.MustCompile(`(?i)^\s*(python(?:3)?|pytest|rscript|bash|sh|go\s+test)\b.+$`)
	seedCmdRE      = regexp.MustCompile(`(?i)--seed\s+(\d+)`)
	seedTextRE     = regexp.MustCompile(`(?i)\bseed\s*[:=]?\s*(\d+)\b`)
	seedErrRE      = regexp.MustCompile(`(?i)seed\s*mismatch[^\n]*?expected\s+(\d+)[^\n]*?got\s+(\d+)`)
)

func (h *Heuristic) ExtractClaims(_ context.Context, paper domain.Paper, _ domain.RepoSummary) ([]domain.Claim, error) {
	lines := strings.Split(paper.Text, "\n")
	claims := make([]domain.Claim, 0)
	seen := map[string]bool{}
	for i, raw := range lines {
		line := strings.TrimSpace(raw)
		if line == "" {
			continue
		}
		id := ""
		text := line
		if m := claimLineRE.FindStringSubmatch(line); m != nil {
			id = strings.ToUpper(m[1])
			text = strings.TrimSpace(m[2])
		}
		metricName := ""
		metricValue := ""
		if before := metricBeforeRE.FindStringSubmatch(text); before != nil {
			metricValue = before[1]
			metricName = before[2]
		} else if after := metricRE.FindStringSubmatch(text); after != nil {
			metricValue = after[2]
			metricName = after[1]
		} else {
			continue
		}
		if id == "" {
			id = fmt.Sprintf("C%d", len(claims)+1)
		}
		if seen[id] {
			id = fmt.Sprintf("%s-%d", id, i+1)
		}
		seen[id] = true
		value, err := strconv.ParseFloat(metricValue, 64)
		if err != nil {
			continue
		}
		tol := domain.Tolerance{Abs: 0.01}
		if tm := toleranceRE.FindStringSubmatch(text); tm != nil {
			if v, err := strconv.ParseFloat(tm[1], 64); err == nil && v > 0 {
				tol.Abs = v
			}
		}
		claims = append(claims, domain.Claim{
			ID:            id,
			Text:          text,
			Metric:        normalizeMetric(metricName),
			ExpectedValue: value,
			Tolerance:     tol,
			Source: domain.ClaimSource{
				Path:  paper.SourcePath,
				Line:  i + 1,
				Quote: line,
			},
		})
	}
	if len(claims) == 0 {
		return nil, fmt.Errorf("no measurable claim found in paper")
	}
	return dedupeClaims(claims), nil
}

func dedupeClaims(claims []domain.Claim) []domain.Claim {
	out := make([]domain.Claim, 0, len(claims))
	index := map[string]int{}
	for _, claim := range claims {
		key := claim.Metric + ":" + strconv.FormatFloat(claim.ExpectedValue, 'g', -1, 64)
		existing, ok := index[key]
		if !ok {
			index[key] = len(out)
			out = append(out, claim)
			continue
		}
		current := out[existing]
		explicitNew := strings.HasPrefix(strings.ToLower(strings.TrimSpace(claim.Source.Quote)), "claim ")
		explicitOld := strings.HasPrefix(strings.ToLower(strings.TrimSpace(current.Source.Quote)), "claim ")
		if claim.Tolerance.Abs > current.Tolerance.Abs || (claim.Tolerance.Abs == current.Tolerance.Abs && explicitNew && !explicitOld) {
			if explicitNew && !explicitOld {
				claim.ID = current.ID
			}
			out[existing] = claim
		}
	}
	return out
}

func (h *Heuristic) BuildPlan(_ context.Context, claim domain.Claim, paper domain.Paper, repo domain.RepoSummary) (*domain.ExperimentPlan, error) {
	command := findCommand(paper.Text)
	if command == "" {
		command = findCommand(repo.Readme)
	}
	if command == "" && len(repo.CommandCandidates) > 0 {
		command = strings.TrimSpace(repo.CommandCandidates[0])
	}
	if command == "" {
		command = "python run_experiment.py"
	}
	seed := 42
	if m := seedCmdRE.FindStringSubmatch(command); m != nil {
		seed, _ = strconv.Atoi(m[1])
	} else if m := seedTextRE.FindStringSubmatch(paper.Text); m != nil {
		seed, _ = strconv.Atoi(m[1])
	}
	metric := normalizeMetric(claim.Metric)
	pattern := `(?i)` + regexp.QuoteMeta(metric) + `\s*[:=]\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+))`
	return &domain.ExperimentPlan{
		ID:             "plan_" + strings.ToLower(claim.ID),
		ClaimID:        claim.ID,
		Command:        command,
		Image:          "python:3.11-slim",
		WorkDir:        ".",
		Seed:           seed,
		ExpectedMetric: metric,
		ExpectedValue:  claim.ExpectedValue,
		Tolerance:      claim.Tolerance,
		MetricSource: domain.MetricSource{
			Kind:    "stdout_regex",
			Pattern: pattern,
			Key:     metric,
		},
		Notes: "Generated by the deterministic offline analyzer.",
	}, nil
}

func (h *Heuristic) Diagnose(_ context.Context, run domain.Run, _ domain.RepoSummary, workspace string) (*domain.Diagnosis, error) {
	output := run.Stderr + "\n" + run.Stdout
	if run.Status == "timeout" {
		return &domain.Diagnosis{
			FailureClass: "timeout",
			RootCause:    "The experiment exceeded the configured execution timeout.",
			Confidence:   "high",
			Explanation:  "No patch is proposed automatically for a timeout; inspect resource usage and command scope.",
		}, nil
	}
	if m := seedErrRE.FindStringSubmatch(output); m != nil {
		want, _ := strconv.Atoi(m[1])
		got, _ := strconv.Atoi(m[2])
		diff, file, err := findSeedPatch(workspace, got, want)
		if err == nil && diff != "" {
			return &domain.Diagnosis{
				FailureClass: "seed_mismatch",
				RootCause:    fmt.Sprintf("The code uses seed %d while the experiment plan requires seed %d.", got, want),
				Confidence:   "high",
				PatchDiff:    diff,
				Explanation:  fmt.Sprintf("Change %s from SEED = %d to SEED = %d without altering the data split or metric.", file, got, want),
			}, nil
		}
	}
	lower := strings.ToLower(output)
	switch {
	case strings.Contains(lower, "modulenotfounderror") || strings.Contains(lower, "no module named"):
		return &domain.Diagnosis{FailureClass: "dependency_missing", RootCause: "A required Python package is not available in the runtime.", Confidence: "high", Explanation: "Pin the dependency in the project environment; no automatic patch is proposed.", NeedsCodeAgent: true}, nil
	case strings.Contains(lower, "filenotfounderror") || strings.Contains(lower, "no such file or directory"):
		return &domain.Diagnosis{FailureClass: "path_error", RootCause: "The command references a missing file or directory.", Confidence: "medium", Explanation: "Check the workspace-relative data and configuration paths before patching.", NeedsCodeAgent: true}, nil
	case strings.Contains(lower, "notimplementederror") || strings.Contains(lower, "not implemented"):
		return &domain.Diagnosis{FailureClass: "missing_implementation", RootCause: "The experiment requires an implementation that is not present in the repository.", Confidence: "high", Explanation: "Delegate the missing implementation to a configured code agent.", NeedsCodeAgent: true}, nil
	case strings.Contains(lower, "syntaxerror"):
		return &domain.Diagnosis{FailureClass: "syntax_error", RootCause: "The repository contains a syntax error.", Confidence: "high", Explanation: "No automatic patch is proposed; inspect the reported source location.", NeedsCodeAgent: true}, nil
	default:
		return &domain.Diagnosis{FailureClass: "unknown", RootCause: "The failure did not match a supported deterministic pattern.", Confidence: "low", Explanation: "Inspect the preserved stdout/stderr and run manifest.", NeedsCodeAgent: true}, nil
	}
}

func findCommand(text string) string {
	lines := strings.Split(text, "\n")
	for _, raw := range lines {
		if m := runLineRE.FindStringSubmatch(raw); m != nil {
			return strings.Trim(strings.TrimSpace(m[1]), "`")
		}
	}
	for _, raw := range lines {
		line := strings.Trim(strings.TrimSpace(raw), "`")
		if codeCmdRE.MatchString(line) {
			return line
		}
	}
	return ""
}

func normalizeMetric(metric string) string {
	metric = strings.ToLower(strings.TrimSpace(metric))
	metric = strings.ReplaceAll(metric, " ", "-")
	if metric == "f1-score" || metric == "f1score" {
		return "f1"
	}
	return metric
}

func findSeedPatch(workspace string, got, want int) (string, string, error) {
	workspace, err := filepath.Abs(workspace)
	if err != nil {
		return "", "", err
	}
	var foundPath, foundContent string
	err = filepath.WalkDir(workspace, func(path string, d os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			if d.Name() == ".git" || d.Name() == "data" || d.Name() == ".reprolens" {
				return filepath.SkipDir
			}
			return nil
		}
		if foundPath != "" || !strings.HasSuffix(strings.ToLower(d.Name()), ".py") {
			return nil
		}
		info, err := d.Info()
		if err != nil || info.Size() > 2<<20 {
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := strings.ReplaceAll(string(b), "\r\n", "\n")
		re := regexp.MustCompile(`(?m)^(\s*SEED\s*=\s*)` + strconv.Itoa(got) + `(\s*)$`)
		if re.MatchString(content) {
			foundPath = path
			foundContent = content
		}
		return nil
	})
	if err != nil {
		return "", "", err
	}
	if foundPath == "" {
		return "", "", fmt.Errorf("seed assignment not found")
	}
	rel, err := filepath.Rel(workspace, foundPath)
	if err != nil {
		return "", "", err
	}
	rel = filepath.ToSlash(rel)
	replacement := regexp.MustCompile(`(?m)^(\s*SEED\s*=\s*)` + strconv.Itoa(got) + `(\s*)$`)
	updated := replacement.ReplaceAllString(foundContent, `${1}`+strconv.Itoa(want)+`${2}`)
	lines := strings.Split(strings.TrimSuffix(foundContent, "\n"), "\n")
	updatedLines := strings.Split(strings.TrimSuffix(updated, "\n"), "\n")
	if len(lines) != len(updatedLines) || len(lines) == 0 {
		return "", "", fmt.Errorf("unexpected seed patch shape")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "--- a/%s\n+++ b/%s\n", rel, rel)
	fmt.Fprintf(&b, "@@ -1,%d +1,%d @@\n", len(lines), len(updatedLines))
	for i := range lines {
		if lines[i] == updatedLines[i] {
			b.WriteString(" " + lines[i] + "\n")
			continue
		}
		b.WriteString("-" + lines[i] + "\n")
		b.WriteString("+" + updatedLines[i] + "\n")
	}
	return b.String(), rel, nil
}
